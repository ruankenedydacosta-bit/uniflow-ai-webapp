const RESPONSE_KINDS = Object.freeze({
  GENERAL_REASONING: 'MOCK_REASONING_RESULT',
  FINANCIAL_REASONING: 'MOCK_FINANCIAL_RESULT',
  CLASSIFICATION: 'MOCK_CLASSIFICATION_RESULT',
  SUMMARIZATION: 'MOCK_SUMMARY_RESULT',
  EXPLANATION: 'MOCK_EXPLANATION_RESULT',
  RECOMMENDATION: 'MOCK_RECOMMENDATION_RESULT',
  FORECAST: 'MOCK_FORECAST_RESULT',
  GOAL_ANALYSIS: 'MOCK_GOAL_RESULT',
  INSIGHT_ANALYSIS: 'MOCK_INSIGHT_RESULT',
  DOCUMENT_ANALYSIS: 'MOCK_DOCUMENT_RESULT',
  VISION: 'MOCK_VISION_RESULT',
  OCR: 'MOCK_OCR_RESULT',
  VOICE: 'MOCK_VOICE_RESULT',
  CALCULATION: 'MOCK_CALCULATION_RESULT',
  BRAINSTORMING: 'MOCK_BRAINSTORM_RESULT',
  CONVERSATION: 'MOCK_CONVERSATION_RESULT',
});

export function createMockCapabilityResponse(capability) {
  const kind = RESPONSE_KINDS[capability];
  if (!kind) return null;
  return {
    kind,
    simulated: true,
    result: {
      status: 'NOT_EVALUATED',
      items: [],
      value: null,
    },
  };
}

export { RESPONSE_KINDS as MOCK_RESPONSE_KINDS };
