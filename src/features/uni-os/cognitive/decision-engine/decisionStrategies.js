export const DECISION_STRATEGIES = Object.freeze([
  'DIRECT',
  'CONFIRM_FIRST',
  'EVIDENCE_WEIGHTED',
  'GOAL_ALIGNED',
  'PRESERVE_PREFERENCE',
  'SAFETY_FIRST',
  'CLARIFY_FIRST',
]);

const STRATEGY_BY_TYPE = Object.freeze({
  DIRECT_RESPONSE: 'DIRECT',
  FINANCIAL_ACTION_CONFIRMATION: 'CONFIRM_FIRST',
  FINANCIAL_ANALYSIS: 'EVIDENCE_WEIGHTED',
  GOAL_GUIDANCE: 'GOAL_ALIGNED',
  CONFIGURATION_CHANGE: 'PRESERVE_PREFERENCE',
  SAFETY_GUIDANCE: 'SAFETY_FIRST',
  CLARIFICATION_REQUEST: 'CLARIFY_FIRST',
});

export function resolveDecisionStrategy(decisionType) {
  return STRATEGY_BY_TYPE[decisionType] ?? 'CLARIFY_FIRST';
}
